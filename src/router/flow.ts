export type StepKey = (typeof STEPS)[number];

/** Три акта. Акт красит сцену и задаёт, где мы находимся физически. */
export type ActId = 'city' | 'lab' | 'assembly';

/**
 * Шаги, сгруппированные по актам. Единственное место, где это записано:
 * обратная карта ниже строится отсюда, разойтись они не могут.
 *
 * Акт I «Город» — человек снаружи, в своей картине мира.
 * Акт II «Лаборатория» — человек внутри LAB 77, разбирает.
 * Акт III «Сборка» — человек допущен и собирает связку целиком.
 *
 * Шаги карты (`map1`, `map2`, `mapfinal`) принадлежат акту города, даже когда
 * идут между лабораторными: выходя на карту, человек физически выходит из
 * лаборатории обратно в Traffic Town, и сцена обязана это показать.
 */
export const ACT_STEPS: Record<ActId, readonly StepKey[]> = {
  city: ['town', 'district', 'chat', 'long1', 'situation', 'zoomout', 'turn'],
  lab: ['lab', 'video1', 'buyers', 'video1end', 'wall1', 'map1', 'long2', 'video2', 'map2'],
  assembly: [
    'barrier',
    'quiz',
    'verdict',
    'long3',
    'video3',
    'mapfinal',
    'exit',
    'long4',
    'offer',
  ],
};

/** Обратная карта: шаг → акт. Построена из `ACT_STEPS`, а не задана руками. */
export const ACT_OF_STEP: Record<StepKey, ActId> = Object.fromEntries(
  (Object.keys(ACT_STEPS) as ActId[]).flatMap((act) =>
    ACT_STEPS[act].map((step) => [step, act]),
  ),
) as Record<StepKey, ActId>;

export function actOfStep(step: StepKey): ActId {
  return ACT_OF_STEP[step];
}

export function stepIndex(step: StepKey): number {
  return STEPS.indexOf(step);
}

/** Следующий шаг или `null` на последнем. */
export function nextStep(step: StepKey): StepKey | null {
  const i = stepIndex(step);
  return i >= 0 && i < STEPS.length - 1 ? STEPS[i + 1] : null;
}

/** Предыдущий шаг или `null` на первом. */
export function prevStep(step: StepKey): StepKey | null {
  const i = stepIndex(step);
  return i > 0 ? STEPS[i - 1] : null;
}


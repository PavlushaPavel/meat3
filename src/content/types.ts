/**
 * Типы контента воронки.
 *
 * Весь текст живёт в `src/content/*` и больше нигде. В компонентах нет ни одной
 * строки копирайта — это правило канона (docs/SPEC.md §4.5), а не совпадение.
 *
 * Ритм авторского текста — короткие абзацы, часто в одно предложение. Каждый
 * абзац здесь отдельный блок: склеивать их в плотные куски запрещено, на этом
 * ритме держится подача.
 */

/** Четыре закона гравитации — они же все состояния мира (docs/SPEC.md §1). */
export type Law = 'updraft' | 'deflect' | 'orbit' | 'anchor';

/** Блок длинного чтения. */
export type Block =
  /** Обычный абзац. */
  | { kind: 'p'; text: string }
  /** Врезка-реплика: то, что в прототипе шло цитатой. Чужой или внутренний голос. */
  | { kind: 'quote'; text: string }
  /** Крупное утверждение, ради которого написан кусок. Одно на раздел, не больше. */
  | { kind: 'lead'; text: string }
  /** Перечисление. Пункты короткие, без точек в конце. */
  | { kind: 'list'; items: string[] }
  /** Подзаголовок внутри длинного чтения. */
  | { kind: 'h'; text: string };

/** Экран длинного чтения на облачной бумаге. */
export interface LongreadContent {
  /** Дисплейный заголовок. Идёт по гнутой базовой линии — держи его коротким. */
  title: string;
  /** Закон, под которым живёт экран: он красит поле и переходы. */
  law: Law;
  blocks: Block[];
  /** Подпись на кнопке перехода дальше. */
  next: string;
}

/** Сообщение клиента во входном чате. */
export interface ChatMessage {
  text: string;
  /** Пауза перед появлением, мс. */
  delayMs: number;
  /**
   * Сколько сообщение висит до того, как клиент его сотрёт, мс.
   * `null` — сообщение остаётся навсегда (последнее, крупное).
   */
  lifetimeMs: number | null;
  /** Крупная подача: только для финального обвинения. */
  big?: boolean;
}

/** Вариант множественного выбора. Ответ ни на что не влияет — он нужен человеку. */
export interface SituationOption {
  id: string;
  text: string;
}

/** Один из пяти покупателей ремонта. */
export interface Buyer {
  id: string;
  /** Короткое имя облака: то, что видно на карточке. */
  label: string;
  /** Ситуация человека, как её увидел бы маркетолог. */
  situation: string;
  /** Закон, по которому летит его капля. */
  law: Law;
  /** Разбор после выбора: что на самом деле происходит с этим человеком. */
  verdict: string;
}

/** Экран видео. Работает и с пустым источником — это требование канона (§3.5). */
export interface VideoContent {
  title: string;
  /** Что человек увидит, одним предложением. Показывается всегда. */
  standfirst: string;
  /** Имя переменной сборки с адресом записи. */
  envVar: 'VITE_VIDEO_1_URL' | 'VITE_VIDEO_2_URL' | 'VITE_VIDEO_3_URL';
  law: Law;
  /** Блоки, которые идут под видео: смысл фрагмента, а не расшифровка. */
  blocks: Block[];
  next: string;
}

/** Кнопка на внешний ресурс. Пустая переменная = честно неактивная кнопка. */
export interface ExternalAction {
  label: string;
  /** Подпись под кнопкой, пока ссылки нет. */
  pending: string;
  envVar:
    | 'VITE_ASSISTANT_AUDIENCE_URL'
    | 'VITE_ASSISTANT_OFFER_URL'
    | 'VITE_CHECKOUT_URL'
    | 'VITE_SUPPORT_URL';
}

/** Тема вопроса — по ней считаем, какой фрагмент человек не понял. */
export type QuizTopic = 'audience' | 'offer';

/** Один ситуационный вопрос допуска. */
export interface QuizQuestion {
  id: string;
  topic: QuizTopic;
  /** Ситуация, а не определение термина. */
  situation: string;
  question: string;
  options: { id: string; text: string }[];
  correctId: string;
  /**
   * Почему верный ответ верный. Показывается ВСЕГДА, и после ошибки тоже:
   * без разбора тест превращается в угадайку (docs/SPEC.md §3.4).
   */
  explanation: string;
}

/**
 * Интерактивы трёх экспериментов.
 *
 * ПОЧЕМУ ИНТЕРАКТИВ РАЗНЫЙ, А ВЫВОД ОДИН. Прежняя врезка спрашивала у всех
 * одно и то же: «кого выбираешь». Для таргетолога это честный вопрос — он
 * действительно выбирает аудиторию. Для директолога это ложь: он не может
 * запретить человеку ввести запрос. Для авитолога — тем более: он не выбирает,
 * кому площадка покажет карточку.
 *
 * Поэтому вопрос задаётся про то, чем человек РЕАЛЬНО управляет:
 *  · Директ — под чью ситуацию строишь гипотезу (объявление, оффер, посадочную);
 *  · Авито — что стоит на первом экране карточки;
 *  · VK — какой сегмент тестируешь первым на бюджет.
 *
 * А вывод после всех трёх один: за запросом, кликом или просмотром всегда
 * стоит человек.
 */

/** Интерактив первого эксперимента: выбор сегмента (Директ и VK). */
export interface SegmentChoice {
  kind: 'segments';
  legend: string;
  /** Рамка вопроса. У Директа она про гипотезу, у VK — про тест бюджетом. */
  setup: string[];
  question: string;
  hint: string;
  cta: string;
  /** Что говорим после выбора, до разбора конкретного образца. */
  afterLead: string;
  after: string[];
  next: string;
}

/** Интерактив первого эксперимента: первый экран карточки (Авито). */
export interface ListingChoice {
  kind: 'listing';
  legend: string;
  setup: string[];
  /** Заголовок карточки, которая уже висит. */
  current: string;
  question: string;
  hint: string;
  options: Array<{
    id: string;
    title: string;
    line: string;
    /** Разбор: кого притягивает и кого отсекает. */
    verdict: string;
    /** Верный ли выбор под человека с ипотекой и арендой. */
    best: boolean;
  }>;
  cta: string;
  afterLead: string;
  after: string[];
  next: string;
}


/**
 * ПЕРСОНАЛИЗАЦИЯ ВОРОНКИ ПО РАЙОНАМ.
 *
 * Решение заказчика 08.08.2026, отменяющее прежнее «имя района подставляем,
 * контент один». Фундамент у всех один — КТО покупает → ПОЧЕМУ покупает →
 * ЧТО ему сказать → КУДА его привести, — но директолог, авитолог и таргетолог
 * приходят к нему разными дорогами. Персонализируем не теорию, а ситуацию,
 * рычаги и язык.
 *
 * ЗАЧЕМ ВСЁ В ОДНОМ ФАЙЛЕ. Соблазн был разложить по экранам: чат к чату,
 * лонгрид к лонгриду. Но тогда, добавляя четвёртый район или правя голос
 * директолога, пришлось бы обойти шесть файлов и один непременно забыть —
 * человек получил бы воронку, которая на пятом экране вдруг заговорила с ним
 * не своим языком. Здесь район читается сверху вниз целиком, и дыра видна
 * глазами.
 *
 * ПРАВИЛО ЯЗЫКА: внутри района говорим его словами и его инструментами
 * (у Директа — семантика и минус-слова, у Авито — просмотры и контакты, у
 * VK — аудитории и CPL). Общие места, где дороги сходятся, говорят нейтрально.
 */

export interface DistrictCopy {
  /** Как человек называет себя. Идёт в печать на экране обвинения. */
  role: string;

  /** Экран «вот твой район»: чем он управляет каждый день. */
  home: {
    lead: string;
    /** Инструменты района. Это его словарь — чужих слов тут быть не должно. */
    tools: string[];
    closing: string;
  };

  /** Сообщения клиента. Копятся в ленте: клиент не стирает, он обвиняет. */
  chat: ChatMessage[];

  /**
   * Первый абзац первого лонгрида: куда человек кинется чинить в первую
   * очередь. Дальше все три дороги сходятся в общий текст.
   */
  firstImpulse: {
    blocks: Block[];
    /** Вопрос, которым абзац заканчивается. У каждого района свой. */
    question: string;
  };

  /** Подзаголовок первого эксперимента. Заголовок общий. */
  experiment1Subtitle: string;

  /** Заголовок второго эксперимента: у Авито просмотр, а не клик. */
  experiment2Title: string;

  /** Персональный финал. Общий вход к нему один на всех. */
  catharsis: {
    opening: string;
    /** Чем он владел, когда пришёл. */
    had: string[];
    /** Что он может теперь. */
    now: string[];
    closing: string[];
  };
}

/** Пауза перед сообщением и «висит навсегда» — клиент ничего не стирает. */
function msg(text: string, delayMs: number): ChatMessage {
  return { text, delayMs, lifetimeMs: null };
}


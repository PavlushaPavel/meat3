import { useEffect, type JSX } from 'react';
import { useFunnel } from './store/funnel';
import { REGISTRY } from './router/registry';
import { FLOW } from './router/flow';
import { initTelegram, setBackButton } from './lib/telegram';

/**
 * Корневой шелл: рендерит текущий шаг из REGISTRY, инициализирует Telegram
 * WebApp при монтировании и привязывает системную кнопку "назад" к goBack —
 * шаг назад идёт системной кнопкой Telegram BackButton, не UI-кнопкой
 * (SPEC.md §3).
 */
export default function App(): JSX.Element {
  const step = useFunnel((s) => s.step);
  const goBack = useFunnel((s) => s.goBack);

  useEffect(() => {
    initTelegram();
  }, []);

  useEffect(() => {
    setBackButton(step > 0, goBack);
    return () => setBackButton(false);
  }, [step, goBack]);

  // Второй, независимый от стора рубеж: store/funnel.ts уже валидирует step
  // при гидратации, но App не обязан доверять этому — при любом step, для
  // которого FLOW не даёт id (или REGISTRY под этим id пуст), рендерится
  // первый шаг маршрута, а не undefined. Приложение не имеет права показать
  // белый экран ни при каком содержимом localStorage.
  const stepId = FLOW[step] ?? FLOW[0];
  const StepScreen = REGISTRY[stepId] ?? REGISTRY[FLOW[0]];

  return <StepScreen />;
}

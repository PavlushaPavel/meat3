import type { Buyer } from '@/content/types';

/**
 * Показания прибора ИИ по каждой из пяти проб сырья (docs/SPEC.md §3.3).
 *
 * Пять покупателей (`src/content/buyers.ts`) стали пятью пробами под
 * анализом: у каждой пробы прибор считает не абстрактный балл и не метрику
 * рекламного результата (кликов, заявок, конверсии — этого прибор про
 * человека знать не может), а две вещи, которые прямо читаются из авторского
 * текста пробы (`situation`/`verdict`, не выдуманы здесь):
 *
 *  - `cause`     — насколько сильна причина купить именно сейчас;
 *  - `readiness` — насколько человек готов действовать сейчас, а не когда-то.
 *
 * Шкала прибора — 10 делений, не проценты: показатель чистоты партии (см.
 * `PurityMeter`) уже занял проценты как единственный сквозной индикатор пути
 * (docs/SPEC.md §3.7), и показание отдельной пробы обязано визуально
 * отличаться от него, а не читаться как второй, конкурирующий прогресс-бар.
 *
 * Откуда взято каждое число — дословно из `src/content/buyers.ts`:
 *  - newbuild: «Причина действовать сейчас у него самая сильная из
 *    пятерых» → `cause` максимальный из пяти. Но «денег в моменте мало» и
 *    решает он «сроком и предсказуемостью», а не ценой → готовность действовать
 *    прямо сейчас реальна, но ограничена — средняя, не высшая.
 *  - secondary: он «не выбирает подрядчика — пытается понять масштаб
 *    проблемы» → причина есть, но не оформлена в решение о покупке; готовность
 *    низкая — «любое предложение с ценой выглядит как обман».
 *  - keys-later: «интерес настоящий, готовность действовать — нет»,
 *    платит «через полгода» → причина заметно выше готовности, разрыв между
 *    ними и есть весь смысл этой пробы.
 *  - old-flat: «нужно закрыть самое больное» — причина конкретная, но
 *    узкая; готовность реальна, но только под другой, более узкий продукт
 *    (не полный ремонт под ключ).
 *  - fedya: «у Феди нет причины покупать. Вообще» → обе шкалы на нуле. Это
 *    не наказание за неверный выбор — это то же самое показание, которое
 *    прибор дал бы любому человеку без причины действовать, попади он под
 *    анализ первым.
 */
export interface ProbeReading {
  /** Причина купить именно сейчас, 0..10 делений прибора. */
  cause: number;
  /** Готовность действовать сейчас, а не когда-нибудь, 0..10 делений прибора. */
  readiness: number;
}

